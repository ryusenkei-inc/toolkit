// 推量・婉曲 → 断定（不明な点は不明と明記）
const HEDGE = /と思[うわいっ]|かもしれな|と考えられ|気がする|おそらく|恐らく|たぶん|多分/;

// 敬体（`です`・`ます`） → 常体・体言止め
const POLITE = /(?:です|ます|でした|ました|ません|ましょう)(?=[。、」）!！?？\s]|$)/;

// 「の」の連続: 名詞を「の」で3回以上接続（4語以上）→ 複合語・語順で解消
//   括弧の中は括弧の外と別の句として判定
//   「の」を含む語（その・もの・のみ・のため・のよう）は接続の「の」から除外
const NO_WORDS = /[そこあど]の|もの|のみ|のため|のよう/g;
const NOUN = '[^\\sのをがにでとはもへや、。・「」（）→:,]+';
const CHAIN = new RegExp(`(?:${NOUN}\\s?の\\s?){3}${NOUN}`, 'u');
// 除外の語・括弧は同じ長さの名詞の文字に置換（位置を保ち、指摘には原文を表示）
const chains = (text: string, prose: string) => {
  const noun = (m: string) => 'Ｘ'.repeat(m.length);
  const masked = prose.replace(NO_WORDS, noun);
  const found: string[] = [];
  const check = (phrase: string, offset: number) => {
    const m = phrase.match(CHAIN);
    // 末尾の括弧は表示から除外（括弧の中は別の句として判定）
    if (m) found.push(text.slice(offset + m.index!, offset + m.index! + m[0].length).replace(/（[^）]*）$/, ''));
  };
  check(masked.replace(/（[^）]*）/g, noun), 0);
  for (const m of masked.matchAll(/（([^）]*)）/g)) check(m[1]!, m.index! + 1);
  return found.map((f) => `「${f}」→ 「の」の連続は 2 つまで（複合語・語順で解消）`);
};

const matchAll = (prose: string, vocabulary: Vocabulary) => vocabulary.flatMap((k) => (prose.match(k.re) ? [`「${prose.match(k.re)![0]}」→ ${k.to}`] : []));

export const styleRules = (vocabulary: Vocabulary): Rule[] => [
  { id: 'style/vocabulary', check: (_, p) => matchAll(p, vocabulary) },
  { id: 'style/verbose', check: (_, p) => matchAll(p, VERBOSE) },
  { id: 'style/chain', check: (t, p) => chains(t, p) },
  { id: 'style/hedge', check: (_, p) => (p.match(HEDGE) ? [`「${p.match(HEDGE)![0]}」→ 断定（不明な点は不明と明記）`] : []) },
  { id: 'style/polite', check: (_, p) => (p.match(POLITE) ? [`「${p.match(POLITE)![0]}」→ 常体・体言止め`] : []) },
];
