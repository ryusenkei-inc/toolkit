// 表記の揺れ: 同じ語の書き方・業界で定着した用語に統一（語の選択・文体は対象外）
//   リポ固有の表記（コード上の名前で書く語など）は設定の `vocabulary`
import type { Rule, Vocabulary } from './rule.ts';

export const NOTATION: Vocabulary = [
  { re: /エントリーポイント/, to: 'エントリポイント' },
  // 長音は語ごとに統一（マスタ・サーバー・インターフェース・ユーザー・メンバー）
  { re: /マスター/, to: 'マスタ' },
  { re: /サーバ(?!ー)/, to: 'サーバー' },
  { re: /インタフェース/, to: 'インターフェース' },
  { re: /ユーザ(?!ー)/, to: 'ユーザー' },
  { re: /メンバ(?!ー)/, to: 'メンバー' },
  // 漢字よりひらがなが一般的な語
  { re: /出来[るなたてまれずよそ]/, to: 'できる' },
  { re: /全て/, to: 'すべて' },
  { re: /又は/, to: 'または' },
  { re: /及び/, to: 'および' },
  { re: /の様[になだで]/, to: 'のように・のような' },
  { re: /下さい/, to: 'ください' },
  { re: /予め/, to: 'あらかじめ' },
  { re: /殆ど/, to: 'ほとんど' },
  { re: /既に/, to: 'すでに' },
  // 「など」の意味の「等」だけ（「同等」「平等」「等しい」「等幅」などは対象外）
  { re: /(?<![同平均対上高初中劣優冗])等(?=[のをがにでは、。）)とも]|$)/, to: 'など' },
  // バージョンの意味の「版」だけ（「出版」「初版」「最新版」「Web 版」などは対象外）
  //   後ろの語で判定する形は、単独の「版」（直前が漢字・カタカナ・英字・空白でない）に限定
  { re: /(同じ|新しい|古い|前の|次の|最新の|各)版|(?<![\p{sc=Han}\p{sc=Katakana}A-Za-z0-9 ])版(を(上げ|固定|指定)|が上が|の(番号|一致|違い)|番号|ごと|間)/u, to: 'バージョン' },
];

export const notationRule = (vocabulary: Vocabulary): Rule => ({
  id: 'format/notation',
  check: (_, p) => vocabulary.flatMap((k) => (p.match(k.re) ? [`「${p.match(k.re)![0]}」→ ${k.to}`] : [])),
});
