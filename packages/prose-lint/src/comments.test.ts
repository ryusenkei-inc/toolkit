import { describe, expect, it } from 'vitest';
import { commentTexts, isGenerated, markdownTexts, wrappedLines } from './comments.ts';

describe('生成物の判定', () => {
  it('先頭の生成の表記で判定', () => {
    expect(isGenerated('/* eslint-disable */\n// Generated by Wrangler by running `wrangler types`')).toBe(true);
    expect(isGenerated('/**\n * This file was automatically generated by Payload.\n * DO NOT MODIFY IT BY HAND.\n */')).toBe(true);
    expect(isGenerated('// Code generated by protoc-gen-go. DO NOT EDIT.\npackage x')).toBe(true);
  });

  it('11行目以降の表記・通常のコメントは対象外', () => {
    expect(isGenerated(`${'const a = 1\n'.repeat(10)}// Generated by Wrangler`)).toBe(false);
    expect(isGenerated('// 記事の取得\nexport const a = 1')).toBe(false);
  });
});

const texts = (source: string, kind: 'slash' | 'hash' = 'slash') => commentTexts(source, kind).map((s) => `${s.line}:${s.text}`);

describe('コメントの検査対象', () => {
  it('行頭の `//` と `/* */`・JSDoc', () => {
    const source = ['// 行のコメント', 'const a = 1; // 行末は対象外', '/**', ' * 説明の行', ' * @param x 引数', ' */', '/* 1 行のブロック */', "const glob = '**/*.ts';"].join('\n');
    expect(texts(source)).toEqual(['1:行のコメント', '4:説明の行', '7:1 行のブロック']);
  });

  it('JSDoc の `@example` とコードブロックは対象外', () => {
    const source = ['/**', ' * 概要', ' * @example', ' * run(作る)', ' * @returns 結果', ' * ```ts', ' * 作る', ' * ```', ' * 最後', ' */'].join('\n');
    expect(texts(source)).toEqual(['2:概要', '9:最後']);
  });

  it('Astro・HTML のコメント', () => {
    const source = ['---', '// フロントマター', '---', '<!-- テンプレート -->', '{/* JSX の式 */}', '<!--', '  複数行', '-->', '<p>本文</p>'].join('\n');
    expect(texts(source)).toEqual(['2:フロントマター', '4:テンプレート', '5:JSX の式', '7:複数行']);
  });

  it('`#` のコメント（shebang は対象外）', () => {
    expect(texts(['#!/usr/bin/env bash', '# 説明', 'echo 1', '// 併用'].join('\n'), 'hash')).toEqual(['2:説明', '4:併用']);
  });

  it('自動修正の範囲は行の中の文だけ', () => {
    const [s] = commentTexts('  /* 本文 */', 'slash');
    expect(s).toEqual({ line: 1, start: 5, end: 7, text: '本文' });
  });
});

describe('文の途中の改行', () => {
  const wrapped = (lines: string[]) => wrappedLines(commentTexts(lines.map((l) => `// ${l}`).join('\n'), 'slash'));

  it('前の行の末尾が読点・助詞、または次の行の先頭が助詞', () => {
    expect(wrapped(['断片の箱は行の上端から配置。既定では最後の行が基準になり、', '本文のベースラインが下がる'])).toEqual([1]);
    expect(wrapped(['キーは判定が割り当てる値で', '方式を差し替えても同じ'])).toEqual([1]);
    expect(wrapped(['結果の分類と状態', 'を IR に含む'])).toEqual([1]);
  });

  it('文の区切りで改行・箇条書き・字下げの補足は対象外', () => {
    expect(wrapped(['plan は探索の計画', 'どちらも1手ごとに更新'])).toEqual([]);
    expect(wrapped(['通し番号が最後の番号に続かないこと', '欠番は取得できない'])).toEqual([]);
    expect(wrapped(['再現の手順は先頭から対象の手順まで', '件数が多い場合は省略'])).toEqual([]);
    expect(wrapped(['対象:', '- 記事と', '- 連載'])).toEqual([]);
    expect(wrapped(['キャッシュの格納は', '  失敗しても継続'])).toEqual([]);
  });
});

describe('Markdown の検査対象', () => {
  it('コードブロック・HTML のコメント・front matter は対象外', () => {
    const source = ['---', 'title: 作る', '---', '本文を作る', '- 手順', '  ```sh', '  作る', '  ```', '~~~', '作る', '~~~', '<!-- 作る', '作る -->', '最後'].join('\n');
    expect(markdownTexts(source).map((t) => t.text)).toEqual(['本文を作る', '手順', '最後']);
  });

  it('引用・タスクのチェックボックス・表の区切り行', () => {
    const source = ['> 引用の文', '> > 入れ子', '- [ ] 未完了', '- [x] 完了', '| A | B |', '| :-- | --: |', '| 値 | 説明 |'].join('\n');
    expect(markdownTexts(source).map((t) => t.text)).toEqual(['引用の文', '入れ子', '未完了', '完了', 'A', 'B', '値', '説明']);
  });
});
